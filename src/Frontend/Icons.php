    /**
     * Echoes a provider logo.
     */
    public static function brand(string $provider, int $size = 20): void
    {
        if (! isset(self::BRANDS[$provider])) {
            self::render('key', $size);
            return;
        }
        $svg = sprintf(
            '<svg class="portier-icon portier-icon--brand" width="%1$d" height="%1$d" viewBox="0 0 24 24" aria-hidden="true" focusable="false">%2$s</svg>',
            $size,
            self::BRANDS[$provider]
        );
        echo wp_kses($svg, self::allowedHtml());
    }

    public static function svg(string $name, int $size = 20, string $class = ''): string
    {
        $paths = self::PATHS[$name] ?? '';
        return sprintf(
            '<svg class="portier-icon %1$s" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%3$s</svg>',
            esc_attr($class),
            $size,
            $paths // Static markup from the constant above.
        );
    }

